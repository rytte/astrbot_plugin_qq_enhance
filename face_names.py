def _normalize_query(value: str) -> str:
    return "".join(unicodedata.normalize("NFKC", value).casefold().split()).strip("/[]")


def lookup_qq_faces(query: str = "", category: str = "all") -> list[dict]:
    """Find all exact ID/name matches, or fall back to name substrings.

    The super filter includes all three upstream super sticker types.
    Duplicate names retain every matching ID. No category is inferred from IDs.
    """

    faces = [
        face
        for face in QQ_FACES
        if category == "all"
        or (category == "super" and face.is_super)
        or face.category == category
    ]
    normalized = _normalize_query(query)
    if normalized:
        exact = [
            face
            for face in faces
            if face.id == normalized or _normalize_query(face.name) == normalized
        ]
        faces = exact or [
            face for face in faces if normalized in _normalize_query(face.name)
        ]
    return [
        {
            "id": face.id,
            "name": face.name,
            "category": face.category,
            "is_super": face.is_super,
            "hidden": face.hidden,
        }
        for face in faces
    ]
